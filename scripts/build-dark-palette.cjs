// Regenerate color-only overrides when globals.css changes. Layout and imagery are preserved.
const fs = require("node:fs");
const postcss = require("postcss");
const input = postcss.parse(fs.readFileSync("app/globals.css", "utf8"));
function hsl(r, g, b) {
  r /= 255;
  g /= 255;
  b /= 255;
  const max = Math.max(r, g, b),
    min = Math.min(r, g, b),
    d = max - min,
    l = (max + min) / 2;
  let h = 0,
    s = 0;
  if (d) {
    s = d / (1 - Math.abs(2 * l - 1));
    h =
      max === r
        ? ((g - b) / d) % 6
        : max === g
          ? (b - r) / d + 2
          : (r - g) / d + 4;
    h *= 60;
    if (h < 0) h += 360;
  }
  return [h, s, l];
}
function convert(token, kind) {
  let r,
    g,
    b,
    a = 1;
  if (token === "white") r = g = b = 255;
  else if (token === "black") r = g = b = 0;
  else if (token[0] === "#") {
    let v = token.slice(1);
    if (v.length === 3 || v.length === 4) v = [...v].map((c) => c + c).join("");
    [r, g, b] = [0, 2, 4].map((i) => parseInt(v.slice(i, i + 2), 16));
    if (v.length === 8) a = parseInt(v.slice(6, 8), 16) / 255;
  } else {
    const c = token.match(/[\d.]+/g).map(Number);
    [r, g, b] = c;
    a = c[3] ?? 1;
  }
  if (!Number.isFinite(r) || !Number.isFinite(g) || !Number.isFinite(b))
    return token;
  let [h, s, l] = hsl(r, g, b);
  if (kind === "shadow") return l < 0.35 ? token : `rgba(0, 0, 0, ${a})`;
  if (kind === "fg") {
    if (l > 0.88) return token; // White text stays white on colored buttons and heroes.
    if (s < 0.15) return `hsla(210, 22%, ${l > 0.45 ? 70 : 89}%, ${a})`;
    return `hsla(${Math.round(h)}, ${Math.round(Math.max(0.35, Math.min(0.7, s)) * 100)}%, ${l > 0.65 ? 79 : l > 0.4 ? 73 : 80}%, ${a})`;
  }
  if (kind === "border")
    return `hsla(${s > 0.2 ? Math.round(h) : 210}, ${s > 0.2 ? 22 : 20}%, ${l > 0.65 ? 27 : 36}%, ${a})`;
  if (l > 0.68)
    return `hsla(${s > 0.18 ? Math.round(h) : 211}, ${s > 0.18 ? 25 : 27}%, ${l > 0.94 ? 12 : 16}%, ${a})`;
  if (l > 0.4)
    return `hsla(${Math.round(h)}, ${Math.round(Math.min(s, 0.6) * 100)}%, 26%, ${a})`;
  return token;
}
function themed(node) {
  if (node.type === "rule") {
    if (node.selector.includes(":root")) return null;
    const out = node.clone({ nodes: [] });
    out.selector = postcss.list
      .comma(node.selector)
      .map((s) => `html[data-theme="dark"] ${s}`)
      .join(",\n");
    for (const d of node.nodes || []) {
      if (
        d.type !== "decl" ||
        d.prop.startsWith("--") ||
        !/^(color|background.*|border.*|box-shadow|text-shadow|fill|stroke|outline.*|accent-color)$/.test(
          d.prop,
        )
      )
        continue;
      const kind = d.prop.includes("shadow")
        ? "shadow"
        : d.prop === "color" || d.prop === "fill" || d.prop === "stroke"
          ? "fg"
          : /border|outline/.test(d.prop)
            ? "border"
            : "bg";
      let val = d.value.replace(
        /#[\da-fA-F]{8}\b|#[\da-fA-F]{6}\b|#[\da-fA-F]{4}\b|#[\da-fA-F]{3}\b|rgba?\([^)]*\)|\bwhite\b|\bblack\b/g,
        (t) => convert(t, kind),
      );
      if (kind === "bg")
        val = val.replace(
          /var\(--(?:green|tf-teal|tf-teal-strong|primary)\)/g,
          "#147a7d",
        );
      if (val !== d.value) out.append(d.clone({ value: val }));
    }
    return out.nodes.length ? out : null;
  }
  if (
    node.type === "atrule" &&
    ["media", "supports", "container"].includes(node.name)
  ) {
    const out = node.clone({ nodes: [] });
    for (const child of node.nodes || []) {
      const c = themed(child);
      if (c) out.append(c);
    }
    return out.nodes.length ? out : null;
  }
  return null;
}
const root = postcss.root();
for (const n of input.nodes) {
  const c = themed(n);
  if (c) root.append(c);
}
fs.writeFileSync(
  "app/dark-palette.css",
  "/* Generated by scripts/build-dark-palette.cjs. Color-only dark palette; no image filters. */\n" +
    root.toString() +
    "\n",
);
